    private static int ActionNearLight(string n, string acts)
    {
        int best = int.MaxValue;
        for (int i = 0; i < n.Length; i++)
        {
            if (n[i] != '灯') continue;
            for (int d = 1; d <= 4 && d < best; d++)
            {
                if (i - d >= 0 && acts.IndexOf(n[i - d]) >= 0) { best = d; break; }
                if (i + d < n.Length && acts.IndexOf(n[i + d]) >= 0) { best = d; break; }
            }
        }
        return best;
    }

    private static bool ContainsAny(string name, params string[] keys)
    {
        foreach (var key in keys)
            if (name.Contains(key, StringComparison.OrdinalIgnoreCase)) return true;
        return false;
    }
