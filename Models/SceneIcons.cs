    private static readonly Geometry Fallback = Geometry.Parse(Sparkle);

    /// <summary>同一份名称在一次会话里会被反复取（列表、首页、桌面各画一次），解析结果按名字缓存。</summary>
    private static readonly Dictionary<string, Geometry> Cache = new(StringComparer.Ordinal);

    public static Geometry For(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return Fallback;

        lock (Cache)
        {
            if (Cache.TryGetValue(name, out var cached)) return cached;
        }

        Geometry geometry = Fallback;
        foreach (var (match, data) in Rules)
        {
            if (!match(name)) continue;
            geometry = Geometry.Parse(data);
            break;
        }

        lock (Cache) Cache[name] = geometry;
        return geometry;
    }

    /// <summary>「开关工作室开灯」里的「开关」是按钮、「玄关筒灯」里的「关」是地名，先摘掉再判开 / 关。</summary>
    private static string Clean(string name) =>
        name.Replace("开关", string.Empty, StringComparison.Ordinal)
            .Replace("玄关", string.Empty, StringComparison.Ordinal);

    private static bool IsLightOff(string name)
    {
        string n = Clean(name);
        if (ContainsAny(n, "全关")) return true;
        int off = ActionNearLight(n, "关熄灭");
        int on = ActionNearLight(n, "开亮启");
        return off <= 4 && on > 4;
    }

    private static bool IsLightOn(string name)
    {
        string n = Clean(name);
        if (ContainsAny(n, "全开")) return true;
        int off = ActionNearLight(n, "关熄灭");
        int on = ActionNearLight(n, "开亮启");
        return on <= 4 && off > 4;
    }

